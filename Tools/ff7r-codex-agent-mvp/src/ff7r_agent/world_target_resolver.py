"""Resolve a human-facing target name to a currently live world position.

Identity and location are deliberately separate concerns:

    display name -> offline identity graph -> live EndCharacterBase row -> XYZ

The identity graph is generated by ``FF7R_Indexer/character_identity_index.py``.
This module never treats a placement row as an active location and never
silently chooses between ambiguous identities.  Placement-only resolution is
reserved for a later, state-aware implementation.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Iterable, Mapping

from .character_locator import scan_character_inventory, scan_character_target
from .navigation_values import MissionError, finite_position


MAX_INDEX_BYTES = 128 * 1024 * 1024
MAX_NAME_LENGTH = 512
INDEX_ENVIRONMENT_VARIABLE = "FF7R_CHARACTER_IDENTITY_INDEX"


def resolve_objective_reference(service: Any, reference: dict[str, Any]) -> dict[str, Any]:
    """Locate a declared marker without discovering or selecting an objective.

    A missing live point falls back to its declared field, never guessed XYZ.
    The objective caller must recheck progress after this potentially slow read.
    """
    from .map_poi import observe_poi, release_poi
    if reference.get('target_type') != 'poi':
        raise MissionError('objective_reference_type_unsupported')
    request_id = None
    try:
        observed = observe_poi(service, reference['target_id'], seconds=10)
        point = observed['poi']
        request_id = point['request_id']
        if (point.get('object_id') != reference.get('object_id')
                or point.get('catalog_sha256') != reference.get('marker_source', {}).get('sha256')):
            raise MissionError('objective_target_catalog_changed')
        return {'status': 'located', 'position': point['position'], 'map_id': point['map_id'],
                'source': point['coordinate_source'], 'authority': 'paired_runtime_coordinate_getters',
                'coordinate_evidence': point}
    except MissionError as exc:
        if str(exc) not in {'poi_observation_timeout', 'poi_socket_or_height_unsupported',
                            'poi_offset_invalid', 'poi_placement_id_unavailable'}:
            raise
        reason = str(exc)
    finally:
        if request_id is not None:
            release_poi(service, request_id)
    field = next((reference.get(key) for key in ('goto_field', 'field', 'location_id')
                  if isinstance(reference.get(key), str) and reference[key]
                  and reference[key] != '0001-WORLD'), None)
    if field is None:
        raise MissionError('objective_macro_destination_unavailable')
    return {'status': 'macro', 'position': None, 'field': field, 'sub_area': None,
            'source': 'MapIconInfo declared destination', 'authority': 'objective_linked_static_field',
            'exact_unavailable_reason': reason}


def _normalise_name(value: str) -> str:
    return value.casefold().strip()


def _validate_name(value: str) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > MAX_NAME_LENGTH:
        raise MissionError("world_target_name_invalid")
    if any(ord(character) < 0x20 or character == "|" for character in value):
        raise MissionError("world_target_name_invalid")
    return value.strip()


def _repo_root() -> Path:
    # .../Tools/ff7r-codex-agent-mvp/src/ff7r_agent/world_target_resolver.py
    return Path(__file__).resolve().parents[4]


def identity_index_candidates() -> list[Path]:
    """Return configured/default index locations in priority order.

    The generated index is intentionally not bundled into the runtime package:
    it is derived from the user's extracted game data.  An explicit argument
    or ``FF7R_CHARACTER_IDENTITY_INDEX`` therefore takes precedence, while the
    standard external location keeps the live bridge zero-configuration after
    the documented offline indexing step.
    """
    candidates: list[Path] = []
    configured = os.environ.get(INDEX_ENVIRONMENT_VARIABLE)
    if configured:
        candidates.append(Path(configured))
    candidates.extend(
        [
            Path(r"C:\CaitGPT\DataTableIndex\Output\Identity\characters.json"),
            _repo_root() / "ProjectKnowledge" / "Current" / "character-identity-index.json",
        ]
    )
    result: list[Path] = []
    seen: set[str] = set()
    for path in candidates:
        key = str(path).casefold()
        if key not in seen:
            seen.add(key)
            result.append(path)
    return result


def load_identity_index(path: str | Path | None = None) -> dict[str, Any]:
    """Load and minimally validate a generated identity graph."""
    candidates = [Path(path)] if path is not None else identity_index_candidates()
    selected = next((candidate for candidate in candidates if candidate.is_file()), None)
    if selected is None:
        raise MissionError("world_target_identity_index_unavailable")
    try:
        if selected.stat().st_size > MAX_INDEX_BYTES:
            raise MissionError("world_target_identity_index_too_large")
        payload = json.loads(selected.read_text(encoding="utf-8"))
    except MissionError:
        raise
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise MissionError("world_target_identity_index_invalid") from exc
    if not isinstance(payload, dict) or not isinstance(payload.get("records"), list):
        raise MissionError("world_target_identity_index_invalid")
    payload = dict(payload)
    payload["index_path"] = str(selected)
    return payload


def _record_map(index: dict[str, Any]) -> dict[str, dict[str, Any]]:
    records = index.get("records")
    if not isinstance(records, list):
        raise MissionError("world_target_identity_index_invalid")
    result: dict[str, dict[str, Any]] = {}
    for record in records:
        if not isinstance(record, dict):
            continue
        canonical_id = record.get("canonical_id")
        if isinstance(canonical_id, str) and canonical_id:
            result[canonical_id] = record
    return result


def _record_values(record: dict[str, Any], index_name: str) -> Iterable[str]:
    if index_name == "display_name":
        values = record.get("display_names", [])
    elif index_name == "planner_character_name":
        values = record.get("planner_character_names", [])
    elif index_name == "localization_key":
        values = record.get("localization_keys", [])
    elif index_name == "placement_object_id":
        values = [(record.get("placement") or {}).get("initialize_transform")]
    else:
        values = [record.get(index_name)]
    if isinstance(values, str):
        values = [values]
    if not isinstance(values, list):
        return []
    return (value for value in values if isinstance(value, str) and value.strip())


def _reverse_index(index: dict[str, Any], index_name: str) -> dict[str, list[str]]:
    raw = index.get("reverse_indexes", {}).get(index_name)
    if isinstance(raw, dict):
        return {
            str(key): [value for value in values if isinstance(value, str)]
            for key, values in raw.items()
            if isinstance(values, list)
        }
    generated: dict[str, list[str]] = {}
    for canonical_id, record in _record_map(index).items():
        for value in _record_values(record, index_name):
            key = _normalise_name(value) if index_name in {
                "display_name",
                "planner_character_name",
                "actor_name",
            } else value
            generated.setdefault(key, []).append(canonical_id)
    return generated


def _lookup(index: dict[str, Any], index_name: str, value: str) -> list[str]:
    reverse = _reverse_index(index, index_name)
    key = _normalise_name(value) if index_name in {
        "display_name",
        "planner_character_name",
        "actor_name",
    } else value
    return list(dict.fromkeys(reverse.get(key, [])))


def _candidate_with_match(
    index: dict[str, Any],
    record: dict[str, Any],
    *,
    match_kind: str,
    matched_value: str,
) -> dict[str, Any]:
    candidate = dict(record)
    candidate["match"] = {"kind": match_kind, "value": matched_value}
    candidate["static_identity_evidence"] = _static_identity_evidence(index, record)
    return candidate


def _static_identity_evidence(
    index: dict[str, Any], record: dict[str, Any]
) -> dict[str, dict[str, Any]]:
    """Describe which canonical records support each runtime identity field.

    Runtime class/CharaSpec matching is only safe when this graph evidence is
    available and its candidate set identifies the selected canonical record.
    Keeping the evidence on the resolved identity also prevents ``locate``
    from silently trusting a hand-built or partially populated candidate.
    """
    result: dict[str, dict[str, Any]] = {}
    for index_name in ("actor_name", "chara_id", "chara_spec_name"):
        value = record.get(index_name)
        if not isinstance(value, str) or not value.strip():
            continue
        canonical_ids = _lookup(index, index_name, value)
        result[index_name] = {
            "value": value,
            "canonical_ids": canonical_ids,
            "candidate_count": len(canonical_ids),
            "unique_to_record": canonical_ids == [record.get("canonical_id")],
        }
    return result


def resolve_identity(name: str, index: dict[str, Any]) -> dict[str, Any]:
    """Resolve a display name or already-known stable identifier.

    Human-facing names use only localisation-backed ``display_names``.  A
    ``PlannerEventChara.Name`` match is reported as evidence but is not
    promoted to a player-facing name, preventing false matches such as an
    arbitrary event role that happens to look readable.
    """
    requested = _validate_name(name)
    records = _record_map(index)
    if not records:
        raise MissionError("world_target_identity_index_empty")

    match_groups: list[tuple[str, list[str]]] = []
    if requested.startswith("$"):
        match_groups.append(("localization_key", _lookup(index, "localization_key", requested)))
    else:
        match_groups.append(("display_name", _lookup(index, "display_name", requested)))
        # These are stable identifiers, not display-name fallbacks.
        for index_name in (
            "canonical_id",
            "actor_name",
            "object_id",
            "placement_object_id",
            "chara_id",
            "chara_spec_name",
        ):
            if index_name == "canonical_id":
                ids = [requested] if requested in records else []
            else:
                ids = _lookup(index, index_name, requested)
            if ids:
                match_groups.append((index_name, ids))
                break

    display_ids = match_groups[0][1] if match_groups else []
    if display_ids:
        match_kind, ids = match_groups[0]
        candidates = [
            _candidate_with_match(
                index,
                records[canonical_id],
                match_kind=match_kind,
                matched_value=requested,
            )
            for canonical_id in ids
            if canonical_id in records
        ]
        if len(candidates) == 1:
            status = "resolved"
            reason = "unique_localized_display_name"
        else:
            status = "ambiguous"
            reason = "display_name_has_multiple_static_candidates"
        return {
            "ok": status == "resolved",
            "status": status,
            "requested_name": requested,
            "candidate_count": len(candidates),
            "candidates": candidates,
            "selection_reason": reason,
            "index_path": index.get("index_path"),
        }

    planner_ids = _lookup(index, "planner_character_name", requested)
    if planner_ids:
        candidates = [
            _candidate_with_match(
                index,
                records[canonical_id],
                match_kind="planner_character_name",
                matched_value=requested,
            )
            for canonical_id in planner_ids
            if canonical_id in records
        ]
        return {
            "ok": False,
            "status": "identity_label_only",
            "requested_name": requested,
            "candidate_count": len(candidates),
            "candidates": candidates,
            "selection_reason": "planner_event_chara_name_is_not_display_name_evidence",
            "index_path": index.get("index_path"),
        }

    # If no human-facing name matched, allow an explicit stable identifier.
    for match_kind, ids in match_groups[1:]:
        candidates = [
            _candidate_with_match(
                index,
                records[canonical_id],
                match_kind=match_kind,
                matched_value=requested,
            )
            for canonical_id in ids
            if canonical_id in records
        ]
        if not candidates:
            continue
        status = "resolved" if len(candidates) == 1 else "ambiguous"
        return {
            "ok": status == "resolved",
            "status": status,
            "requested_name": requested,
            "candidate_count": len(candidates),
            "candidates": candidates,
            "selection_reason": f"unique_{match_kind}" if status == "resolved" else f"{match_kind}_has_multiple_candidates",
            "index_path": index.get("index_path"),
        }

    return {
        "ok": False,
        "status": "unknown",
        "requested_name": requested,
        "candidate_count": 0,
        "candidates": [],
        "selection_reason": "no_localized_display_or_stable_identifier_match",
        "index_path": index.get("index_path"),
    }


def _class_matches(candidate: dict[str, Any], runtime_class: str) -> bool:
    if not isinstance(runtime_class, str) or not runtime_class:
        return False
    spec = candidate.get("chara_spec_name")
    if not isinstance(spec, str) or not spec:
        return False
    short_spec = spec.removeprefix("CharaSpec_")
    return short_spec in runtime_class or spec in runtime_class


def _match_runtime_actor(
    candidate: dict[str, Any], actor: dict[str, Any]
) -> tuple[int, list[dict[str, Any]], str | None]:
    """Score a live actor only when static identity evidence is sufficient.

    A runtime row matching a shared CharaSpec/class is not enough: another
    canonical identity may use that same class.  Multiple runtime fields may
    still identify the candidate when the intersection of their static
    canonical-id sets is exactly the requested identity.
    """
    score = 0
    evidence: list[dict[str, Any]] = []
    static_evidence = candidate.get("static_identity_evidence")
    if not isinstance(static_evidence, dict):
        return 0, [], "runtime_identity_has_no_static_uniqueness_evidence"
    matched_sets: list[set[str]] = []

    def add_match(
        field: str,
        value: str,
        points: int,
        *,
        static_field: str,
    ) -> None:
        nonlocal score
        scope = static_evidence.get(static_field)
        if not isinstance(scope, dict):
            return
        canonical_ids = {
            item for item in scope.get("canonical_ids", []) if isinstance(item, str)
        }
        if not canonical_ids:
            return
        score += points
        matched_sets.append(canonical_ids)
        evidence.append(
            {
                "field": field,
                "value": value,
                "static_identity_field": static_field,
                "static_canonical_ids": sorted(canonical_ids),
                "static_candidate_count": len(canonical_ids),
                "static_unique_to_record": len(canonical_ids) == 1,
            }
        )

    actor_name = candidate.get("actor_name")
    if isinstance(actor_name, str) and actor_name and actor.get("actor_name") == actor_name:
        add_match("actor_name", actor_name, 100, static_field="actor_name")

    chara_spec = candidate.get("chara_spec_name")
    if isinstance(chara_spec, str) and chara_spec and actor.get("chara_spec") == chara_spec:
        add_match("chara_spec", chara_spec, 60, static_field="chara_spec_name")

    chara_id = candidate.get("chara_id")
    if isinstance(chara_id, str) and chara_id and actor.get("chara_id") == chara_id:
        add_match("chara_id", chara_id, 40, static_field="chara_id")

    if _class_matches(candidate, actor.get("class", "")):
        if isinstance(chara_spec, str) and chara_spec:
            add_match(
                "class_chara_spec",
                chara_spec,
                30,
                static_field="chara_spec_name",
            )

    if not matched_sets:
        return 0, evidence, "runtime_fields_have_no_static_match_scope"
    intersection = set.intersection(*matched_sets)
    canonical_id = candidate.get("canonical_id")
    if not isinstance(canonical_id, str) or intersection != {canonical_id}:
        return 0, evidence, "runtime_identity_evidence_is_not_unique_in_static_graph"
    return score, evidence, None


def _placement_status(candidate: dict[str, Any]) -> str:
    placement = candidate.get("placement")
    if isinstance(placement, dict) and placement.get("initialize_transform"):
        return "known_but_not_currently_instantiated"
    return "known_but_no_runtime_location"


def locate_identity(
    service: Any,
    identity: dict[str, Any],
    *,
    seconds: int = 60,
) -> dict[str, Any]:
    """Locate one resolved identity in the on-demand live inventory."""
    if not isinstance(identity, dict):
        raise MissionError("world_target_identity_invalid")
    if identity.get("status") != "resolved" or identity.get("candidate_count") != 1:
        return {
            "ok": False,
            "status": identity.get("status", "identity_unresolved"),
            "identity": identity,
            "selection_reason": "identity_must_be_unique_before_live_matching",
        }

    candidate = (identity.get("candidates") or [None])[0]
    if not isinstance(candidate, dict):
        raise MissionError("world_target_identity_invalid")

    # A named character can be located with the bounded exact-target probe.
    # Prefer it when the identity graph provides an actor name; the full
    # inventory remains the fallback for identities that need class-wide
    # matching (for example, a blank actor name with only a unique class).
    actor_name = candidate.get("actor_name")
    if isinstance(actor_name, str) and actor_name.strip():
        try:
            fast_scan = scan_character_target(
                service,
                f"actor_name:{actor_name}",
                seconds=seconds,
            )
        except Exception:
            fast_scan = None
        snapshot = fast_scan.get("snapshot") if isinstance(fast_scan, dict) else None
        actor = snapshot.get("target") if isinstance(snapshot, dict) else None
        if (
            isinstance(snapshot, dict)
            and snapshot.get("complete") is True
            and isinstance(actor, dict)
        ):
            score, evidence, blocked_reason = _match_runtime_actor(candidate, actor)
            if score:
                try:
                    position = finite_position(actor.get("position"))
                except MissionError:
                    return {
                        "ok": False,
                        "status": "live_actor_missing_position",
                        "canonical_id": candidate.get("canonical_id"),
                        "identity": identity,
                        "live_actor": actor,
                        "selection_reason": "matching_live_actor_has_no_finite_xyz",
                    }
                sample = fast_scan.get("sample") if isinstance(fast_scan.get("sample"), dict) else {}
                return {
                    "ok": True,
                    "status": "located",
                    "requested_name": identity.get("requested_name"),
                    "canonical_id": candidate.get("canonical_id"),
                    "identity": identity,
                    "location": position,
                    "position": position,
                    "source": "live_actor",
                    "location_source": "live_actor",
                    "coordinate_source": "K2_GetActorLocation",
                    "location_quality": "authoritative_live",
                    "map_id": sample.get("map_id"),
                    "sample_sequence": sample.get("sequence"),
                    "live_actor": actor,
                    "match_evidence": evidence,
                    "selection_reason": "unique_best_live_actor_identity_match",
                }
            if blocked_reason and evidence:
                chosen = _caller_selected_live_actor(identity, candidate, [actor], [evidence], fast_scan)
                if chosen is not None:
                    return chosen
                return {
                    "ok": False,
                    "status": "live_actor_identity_ambiguous",
                    "canonical_id": candidate.get("canonical_id"),
                    "identity": identity,
                    "candidate_count": 1,
                    "live_candidates": [actor],
                    "blocked_match_evidence": [evidence],
                    "selection_reason": "live_actor_matches_only_non_unique_static_identity_evidence",
                }

    scan = scan_character_inventory(service, seconds=seconds)
    snapshot = scan.get("snapshot") if isinstance(scan, dict) else None
    if not isinstance(snapshot, dict):
        raise MissionError("world_target_character_inventory_invalid")
    rows = snapshot.get("characters")
    if not isinstance(rows, list):
        raise MissionError("world_target_character_inventory_invalid")

    scored: list[tuple[int, dict[str, Any], list[dict[str, Any]]]] = []
    blocked: list[tuple[dict[str, Any], list[dict[str, Any]], str]] = []
    for row in rows:
        if not isinstance(row, dict) or row.get("is_player") is True:
            continue
        score, evidence, blocked_reason = _match_runtime_actor(candidate, row)
        if score:
            scored.append((score, row, evidence))
        elif evidence and blocked_reason:
            blocked.append((row, evidence, blocked_reason))

    if not scored:
        if blocked:
            chosen = _caller_selected_live_actor(identity, candidate, [row for row, _, _ in blocked],
                                                 [evidence for _, evidence, _ in blocked], scan)
            if chosen is not None:
                return chosen
            return {
                "ok": False,
                "status": "live_actor_identity_ambiguous",
                "canonical_id": candidate.get("canonical_id"),
                "identity": identity,
                "candidate_count": len(blocked),
                "live_candidates": [row for row, _, _ in blocked],
                "blocked_match_evidence": [evidence for _, evidence, _ in blocked],
                "selection_reason": "live_actor_matches_only_non_unique_static_identity_evidence",
            }
        return {
            "ok": False,
            "status": _placement_status(candidate),
            "canonical_id": candidate.get("canonical_id"),
            "identity": identity,
            "map_id": (scan.get("sample") or {}).get("map_id"),
            "selection_reason": "no_matching_live_end_character_base_actor",
            "location_source": None,
            "placement": candidate.get("placement"),
        }

    best_score = max(score for score, _, _ in scored)
    best = [(row, evidence) for score, row, evidence in scored if score == best_score]
    if len(best) != 1:
        return {
            "ok": False,
            "status": "live_actor_ambiguous",
            "canonical_id": candidate.get("canonical_id"),
            "identity": identity,
            "candidate_count": len(best),
            "live_candidates": [row for row, _ in best],
            "selection_reason": "multiple_live_actors_share_best_identity_evidence",
        }

    actor, match_evidence = best[0]
    try:
        position = finite_position(actor.get("position"))
    except MissionError:
        return {
            "ok": False,
            "status": "live_actor_missing_position",
            "canonical_id": candidate.get("canonical_id"),
            "identity": identity,
            "live_actor": actor,
            "selection_reason": "matching_live_actor_has_no_finite_xyz",
        }
    sample = scan.get("sample") if isinstance(scan.get("sample"), dict) else {}
    return {
        "ok": True,
        "status": "located",
        "requested_name": identity.get("requested_name"),
        "canonical_id": candidate.get("canonical_id"),
        "identity": identity,
        "location": position,
        "position": position,
        "source": "live_actor",
        "location_source": "live_actor",
        "coordinate_source": "K2_GetActorLocation",
        "location_quality": "authoritative_live",
        "map_id": sample.get("map_id"),
        "sample_sequence": sample.get("sequence"),
        "live_actor": actor,
        "match_evidence": match_evidence,
        "selection_reason": "unique_best_live_actor_identity_match",
    }


def _caller_selected_live_actor(identity: Mapping[str, Any], candidate: Mapping[str, Any],
                                actors: list[dict[str, Any]], evidence: list[Any],
                                scan: Any) -> dict[str, Any] | None:
    """Accept the one live actor for a record the caller named by canonical id.

    A class shared by several static records (live: Chadley's model is used by
    eleven records across four areas) cannot say which record a live actor is,
    so a name alone fails closed. When the caller names one record by its
    canonical id and exactly one live actor matches it, the caller has done
    the disambiguation.
    """
    requested = str(identity.get("requested_name") or "")
    if not requested or requested != str(candidate.get("canonical_id") or "") or len(actors) != 1:
        return None
    actor = actors[0]
    try:
        position = finite_position(actor.get("position"))
    except MissionError:
        return None
    sample = (scan.get("sample") if isinstance(scan, dict) else None) or {}
    return {
        "ok": True,
        "status": "located",
        "requested_name": requested,
        "canonical_id": candidate.get("canonical_id"),
        "identity": identity,
        "location": position,
        "position": position,
        "source": "live_actor",
        "location_source": "live_actor",
        "coordinate_source": "K2_GetActorLocation",
        "location_quality": "caller_disambiguated_live",
        "map_id": sample.get("map_id") if isinstance(sample, dict) else None,
        "sample_sequence": sample.get("sequence") if isinstance(sample, dict) else None,
        "live_actor": actor,
        "match_evidence": evidence[0] if evidence else None,
        "selection_reason": "caller_selected_canonical_id_unique_live_match",
    }


def resolve_world_target(
    service: Any,
    name: str,
    *,
    seconds: int = 60,
    identity_index_path: str | Path | None = None,
) -> dict[str, Any]:
    """Resolve a human name and locate its current live actor, fail closed."""
    index = load_identity_index(identity_index_path)
    identity = resolve_identity(name, index)
    if identity.get("status") != "resolved":
        return {
            "ok": False,
            "status": identity.get("status"),
            "requested_name": identity.get("requested_name"),
            "identity": identity,
            "location": None,
        }
    return locate_identity(service, identity, seconds=seconds)
